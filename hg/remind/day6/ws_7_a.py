my_list = [1, 2, 3]
my_dict = {'A': 1, 'B': 2, 'C': 3}

# dir 함수를 사용하여 메서드 목록 출력
#print("--- my_lsit dir ---")
print(dir(my_list))

#print("\n--- my_dict dir ---")
print(dir(my_dict))

# help 함수를 사용하여 구성 출력
#print("\n--- my_lsit help ---")
print(help(my_list))

#print("\n--- my_dict help ---")
print(help(my_dict))